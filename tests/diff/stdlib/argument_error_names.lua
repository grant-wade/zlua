-- feature: argument-error-diagnostics
-- normalize: none

-- Library errors raised for Lua callers carry the caller's position, name the
-- function from the call site, renumber method arguments, and tell a missing
-- argument ("no value") from an explicit nil. Callers that are library
-- functions themselves (pcall here) give no position or call-site name.

local function check(fn, ...)
  local ok, err = pcall(fn, ...)
  if ok then
    print(true, err)
  else
    print(false, (tostring(err):gsub("[^%s]*:(%d+): ", "chunk:%1: ")))
  end
end

